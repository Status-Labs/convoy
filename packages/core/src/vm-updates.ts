// Keeping VMs up to date. Every VM gets the same setup files (setupFiles) at
// first boot through cloud-init, and again over SSH from `convoy update`
// (updateScript). Both then run vm-setup/converge.sh, which is safe to repeat
// and records SETUP_VERSION in /etc/convoy/version. The CLI compares that
// with its own SETUP_VERSION to tell the user a VM needs updating.

import { readdirSync, readFileSync } from "node:fs";
import { GH_INSTALL } from "./github";
import { GLAB_INSTALL } from "./gitlab";
import { AGENT_TOOLS } from "./tools";

/**
 * Changes to what's on a VM, newest last. Add an entry, with the next
 * version, whenever a change touches vm-setup/, tools.ts or the GitHub or
 * GitLab install steps. Mark it `security` if VMs should update promptly.
 */
export const SETUP_RELEASES: readonly { version: number; note: string; security?: boolean }[] = [
  { version: 1, note: "VMs can be updated in place with `convoy update`" },
];

export const SETUP_VERSION = SETUP_RELEASES.at(-1)!.version;

export interface SetupFile {
  path: string;
  content: string;
  permissions: string;
}

function setupFile(name: string): string {
  return readFileSync(new URL(`./vm-setup/${name}`, import.meta.url), "utf8");
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

function indent(lines: string): string {
  return lines
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

/** Bash functions converge.sh uses to install or update the CLIs and agent tools. */
function toolsScript(): string {
  const cases = AGENT_TOOLS.map((tool) =>
    [
      `    ${tool.id})`,
      `      log ${shellQuote(`installing ${tool.name}`)}`,
      `      phase ${shellQuote(`adding ${tool.name}`)}`,
      `      as_agent ${shellQuote(tool.install)}`,
      `      as_agent ${shellQuote(`command -v ${tool.bin} >/dev/null`)} || { log ${shellQuote(`${tool.bin} missing after install`)}; return 1; }`,
      "      ;;",
    ].join("\n"),
  );
  return [
    "# Generated by convoy from tools.ts, github.ts and gitlab.ts. Sourced by converge.sh.",
    "",
    "install_gh() {",
    indent(GH_INSTALL),
    "}",
    "",
    "install_glab() {",
    indent(GLAB_INSTALL),
    "}",
    "",
    "install_tool() {",
    '  case "$1" in',
    ...cases,
    `    *) log "unknown tool $1, skipped" ;;`,
    "  esac",
    "}",
    "",
  ].join("\n");
}

function migrations(): SetupFile[] {
  const dir = new URL("./vm-setup/migrations/", import.meta.url);
  return readdirSync(dir)
    .filter((name) => /^\d{4}-.+\.sh$/.test(name))
    .sort()
    .map((name) => ({
      path: `/usr/local/lib/convoy/migrations/${name}`,
      content: readFileSync(new URL(name, dir), "utf8"),
      permissions: "0644",
    }));
}

/** Files Convoy owns on every VM, written at first boot and replaced by each update. */
export function setupFiles(): SetupFile[] {
  return [
    { path: "/etc/ssh/sshd_config.d/00-convoy.conf", content: setupFile("sshd.conf"), permissions: "0644" },
    { path: "/etc/fail2ban/jail.d/convoy.local", content: setupFile("fail2ban.local"), permissions: "0644" },
    { path: "/etc/apt/apt.conf.d/20auto-upgrades", content: setupFile("auto-upgrades.conf"), permissions: "0644" },
    { path: "/etc/sysctl.d/99-convoy.conf", content: setupFile("sysctl.conf"), permissions: "0644" },
    { path: "/etc/apparmor.d/convoy-chrome", content: setupFile("convoy-chrome.apparmor"), permissions: "0644" },
    { path: "/usr/local/sbin/convoy-firewall", content: setupFile("convoy-firewall.sh"), permissions: "0755" },
    { path: "/usr/local/lib/convoy/bootstrap.sh", content: setupFile("bootstrap.sh"), permissions: "0755" },
    { path: "/usr/local/lib/convoy/converge.sh", content: setupFile("converge.sh"), permissions: "0755" },
    { path: "/usr/local/lib/convoy/desktop.sh", content: setupFile("desktop.sh"), permissions: "0755" },
    { path: "/usr/local/lib/convoy/tools.sh", content: toolsScript(), permissions: "0644" },
    { path: "/usr/local/lib/convoy/setup-version", content: `${SETUP_VERSION}\n`, permissions: "0644" },
    ...migrations(),
  ];
}

/**
 * Root script (run with `sudo bash -s`) that brings an existing VM to this
 * Convoy's setup: writes the setup files, drops migrations this Convoy no
 * longer ships, then runs converge.sh. Holds no secrets.
 */
export function updateScript(): string {
  const files = setupFiles();
  const lines = ["set -euo pipefail", "rm -rf /usr/local/lib/convoy/migrations"];
  for (const file of files) {
    const encoded = Buffer.from(file.content).toString("base64");
    lines.push(
      `install -d -m 0755 ${shellQuote(file.path.slice(0, file.path.lastIndexOf("/")))}`,
      `base64 -d > ${shellQuote(file.path)} <<'CONVOY_FILE'`,
      ...(encoded.match(/.{1,76}/g) ?? []),
      "CONVOY_FILE",
      `chmod ${file.permissions} ${shellQuote(file.path)}`,
    );
  }
  // stdin is this script; keep installers from reading it.
  lines.push("bash /usr/local/lib/convoy/converge.sh </dev/null");
  return lines.join("\n") + "\n";
}

export type UpdateState = "current" | "available" | "security" | "newer";

export interface UpdateStatus {
  state: UpdateState;
  /** The VM's setup version; 0 for VMs set up before versions existed. */
  version: number;
  /** What the update brings, oldest first. */
  notes: string[];
}

/** How a VM's setup version compares with this Convoy's. */
export function updateStatus(version: number): UpdateStatus {
  if (version > SETUP_VERSION) return { state: "newer", version, notes: [] };
  const pending = SETUP_RELEASES.filter((r) => r.version > version);
  if (pending.length === 0) return { state: "current", version, notes: [] };
  return {
    state: pending.some((r) => r.security) ? "security" : "available",
    version,
    notes: pending.map((r) => r.note),
  };
}

/** One line for the user about a VM's update status, or null if it's current. */
export function updateMessage(name: string, status: UpdateStatus): string | null {
  switch (status.state) {
    case "current":
      return null;
    case "newer":
      return `${name} was set up by a newer Convoy (setup v${status.version}); update this Convoy (git pull) before running update on it.`;
    case "security":
      return `${name} needs a security update (setup v${status.version} → v${SETUP_VERSION}).`;
    case "available":
      return `${name} has an update (setup v${status.version} → v${SETUP_VERSION}).`;
  }
}

/** Prints the VM's setup version (0 if it predates versions) and `reboot` if one is pending. Run as any user. */
export const UPDATE_CHECK_SCRIPT = `
if [ -f /etc/convoy/version ]; then cat /etc/convoy/version; else echo 0; fi
if [ -f /var/run/reboot-required ]; then echo reboot; fi
`;

export function parseUpdateCheck(stdout: string): { version: number; rebootRequired: boolean } {
  const [first = "0", ...rest] = stdout.trim().split("\n");
  const version = Number.parseInt(first, 10);
  return { version: Number.isFinite(version) ? version : 0, rebootRequired: rest.includes("reboot") };
}
