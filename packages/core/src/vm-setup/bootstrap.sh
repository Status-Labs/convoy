#!/bin/bash
# Runs once as root at first boot (from cloud-init runcmd), after packages are
# upgraded and the config files from write_files are in place. Does what only
# a new machine needs, then converge.sh applies the security baseline and
# installs the tools. `convoy update` runs converge.sh again later.
set -euo pipefail

STATE_DIR=/var/lib/convoy
LIB=/usr/local/lib/convoy

step="starting"
log() {
  step="$*"
  echo "[convoy] $*"
}
# A short label for the CLI's progress display (it reads $STATE_DIR/phase).
phase() {
  echo "$*" > "$STATE_DIR/phase"
}

# The CLI reads these markers to report the outcome; cloud-init's own status
# isn't reliable after a reboot.
mkdir -p "$STATE_DIR" /etc/convoy
rm -f "$STATE_DIR/ready" "$STATE_DIR/failed"
phase "securing the VM"
trap 'rc=$?; if [ "$rc" -ne 0 ]; then echo "$step" > "$STATE_DIR/failed"; fi' EXIT

# DigitalOcean gives root an expired password when no SSH keys are passed via
# its API, which breaks sudo and cron for root. Root never logs in here, so
# lock the password and clear the forced change.
log "locking root password"
usermod -L root
chage -d "$(date +%F)" -M -1 root

# A new VM already has what every migration so far would change.
latest=$(find "$LIB/migrations" -name '[0-9]*.sh' -printf '%f\n' 2>/dev/null | sort | tail -n1 | cut -d- -f1)
echo "${latest:-0}" > /etc/convoy/migration

# shellcheck source=/dev/null
. "$LIB/converge.sh"

# Extras picked at launch (Tailscale, desktop), generated by cloud-init.ts.
# Later runs of converge.sh keep them up to date.
# shellcheck source=/dev/null
. "$LIB/install-extras.sh"

rm -f "$STATE_DIR/phase"
date -u +%FT%TZ > "$STATE_DIR/ready"
log "setup complete"
