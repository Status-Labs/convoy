// First-boot config for agent VMs, shared by every provider. Creates an
// `agent` user with the given SSH key, applies the security baseline and
// installs the selected agent tools (see vm-setup/bootstrap.sh).

import { readFileSync } from "node:fs";
import { stringify } from "yaml";
import { AGENT_TOOLS, type ToolId } from "./tools";

export interface CloudInitOptions {
  sshPublicKey: string;
  tools: ToolId[];
}

// Our own user rather than the image default, which differs per provider
// (ubuntu on OVH, root on DigitalOcean).
export const VM_USER = "agent";

function setupFile(name: string): string {
  return readFileSync(new URL(`./vm-setup/${name}`, import.meta.url), "utf8");
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

function installToolsScript(tools: ToolId[]): string {
  const lines = ["# Generated by agent-vm from the selected tools. Sourced by bootstrap.sh."];
  for (const tool of AGENT_TOOLS.filter((t) => tools.includes(t.id))) {
    lines.push(
      "",
      `log ${shellQuote(`installing ${tool.name}`)}`,
      `as_agent ${shellQuote(tool.install)}`,
      `as_agent ${shellQuote(`command -v ${tool.bin} >/dev/null`)} || { log ${shellQuote(`${tool.bin} missing after install`)}; exit 1; }`,
    );
  }
  return lines.join("\n") + "\n";
}

const SSHD_CONFIG = `# agent-vm baseline. Loaded before cloud-init's 50-cloud-init.conf; sshd uses the first value it reads.
PermitRootLogin no
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
AuthenticationMethods publickey
AllowUsers ${VM_USER}
MaxAuthTries 3
LoginGraceTime 30
X11Forwarding no
`;

const FAIL2BAN_JAIL = `[sshd]
enabled = true
backend = systemd
maxretry = 5
findtime = 10m
bantime = 1h
`;

const AUTO_UPGRADES = `APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
`;

const SYSCTL = `# agent-vm baseline network hardening
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.default.accept_redirects = 0
net.ipv6.conf.all.accept_redirects = 0
net.ipv6.conf.default.accept_redirects = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.all.accept_source_route = 0
net.ipv6.conf.all.accept_source_route = 0
net.ipv4.icmp_echo_ignore_broadcasts = 1
net.ipv4.tcp_syncookies = 1
kernel.kptr_restrict = 2
kernel.dmesg_restrict = 1
`;

// Docker isn't installed by default, but if it is later, published ports
// bind to localhost unless a host IP is given explicitly.
const DOCKER_DAEMON = `${JSON.stringify({ ip: "127.0.0.1" }, null, 2)}\n`;

export function buildCloudInit({ sshPublicKey, tools }: CloudInitOptions): string {
  const config = {
    users: [
      {
        name: VM_USER,
        groups: ["sudo"],
        shell: "/bin/bash",
        sudo: "ALL=(ALL) NOPASSWD:ALL",
        ssh_authorized_keys: [sshPublicKey.trim()],
      },
    ],
    disable_root: true,
    ssh_pwauth: false,

    package_update: true,
    package_upgrade: true,
    packages: [
      // security baseline
      "ufw",
      "fail2ban",
      "python3-systemd",
      "unattended-upgrades",
      // toolchain
      "git",
      "curl",
      "ca-certificates",
      "unzip",
      "build-essential",
      "python3",
      "python3-pip",
      "python3-venv",
      "ripgrep",
      "jq",
      "tmux",
    ],

    write_files: [
      { path: "/etc/ssh/sshd_config.d/00-agent-vm.conf", content: SSHD_CONFIG, permissions: "0644" },
      { path: "/etc/fail2ban/jail.d/agent-vm.local", content: FAIL2BAN_JAIL, permissions: "0644" },
      { path: "/etc/apt/apt.conf.d/20auto-upgrades", content: AUTO_UPGRADES, permissions: "0644" },
      { path: "/etc/sysctl.d/99-agent-vm.conf", content: SYSCTL, permissions: "0644" },
      { path: "/etc/docker/daemon.json", content: DOCKER_DAEMON, permissions: "0644" },
      { path: "/etc/agent-vm/tools", content: tools.join("\n") + "\n", permissions: "0644" },
      { path: "/usr/local/sbin/agent-vm-firewall", content: setupFile("agent-vm-firewall.sh"), permissions: "0755" },
      { path: "/usr/local/lib/agent-vm/bootstrap.sh", content: setupFile("bootstrap.sh"), permissions: "0755" },
      { path: "/usr/local/lib/agent-vm/install-tools.sh", content: installToolsScript(tools), permissions: "0644" },
    ],

    runcmd: [["bash", "/usr/local/lib/agent-vm/bootstrap.sh"]],

    // The first-boot upgrade often installs a new kernel. Reboot once, after
    // all setup is done, so the VM runs it.
    power_state: {
      mode: "reboot",
      condition: "test -f /var/run/reboot-required",
      message: "agent-vm: rebooting to apply updates",
    },
  };

  return `#cloud-config\n${stringify(config, { lineWidth: 0 })}`;
}
