// First-boot config for agent VMs, shared by every provider. Creates an
// `agent` user with the given SSH key, writes Convoy's setup files and runs
// vm-setup/bootstrap.sh, which applies the security baseline and installs the
// selected agent tools. `convoy update` brings the same files to existing VMs
// (see vm-updates.ts).

import { stringify } from "yaml";
import { TAILSCALE_INSTALL } from "./tailscale";
import { type ToolId } from "./tools";
import { setupFiles } from "./vm-updates";

export interface CloudInitOptions {
  sshPublicKey: string;
  tools: ToolId[];
  /** Install Tailscale; the CLI joins the VM to the tailnet after setup. */
  tailscale?: boolean;
  /** Install the browser-viewable Linux desktop (see vm-setup/desktop.sh). */
  desktop?: boolean;
}

// Our own user rather than the image default, which differs per provider
// (ubuntu on OVH, root on DigitalOcean).
export const VM_USER = "agent";

/** Root script that installs the desktop on an existing VM (run with `sudo bash -s`). */
export function desktopInstallScript(): string {
  return setupFiles().find((f) => f.path.endsWith("/desktop.sh"))!.content;
}

// Extras picked at launch. Only first boot installs them; converge.sh keeps
// whatever is installed up to date.
function installExtrasScript(tailscale: boolean, desktop: boolean): string {
  const lines = ["# Generated by convoy from the launch options. Sourced by bootstrap.sh."];
  if (tailscale) lines.push("", "phase 'adding Tailscale'", "log 'installing Tailscale'", TAILSCALE_INSTALL);
  if (desktop) lines.push("", "phase 'adding desktop'", "log 'installing desktop'", "bash /usr/local/lib/convoy/desktop.sh");
  return lines.join("\n") + "\n";
}

// Docker isn't installed by default, but if it is later, published ports
// bind to localhost unless a host IP is given explicitly. First boot only, so
// an update never overwrites the user's own Docker settings.
const DOCKER_DAEMON = `${JSON.stringify({ ip: "127.0.0.1" }, null, 2)}\n`;

export function buildCloudInit({ sshPublicKey, tools, tailscale = false, desktop = false }: CloudInitOptions): string {
  const config = {
    users: [
      {
        name: VM_USER,
        groups: ["sudo"],
        shell: "/bin/bash",
        sudo: "ALL=(ALL) NOPASSWD:ALL",
        ssh_authorized_keys: [sshPublicKey.trim()],
      },
    ],
    disable_root: true,
    ssh_pwauth: false,

    // converge.sh installs Convoy's packages, so updates can add more.
    package_update: true,
    package_upgrade: true,

    write_files: [
      ...setupFiles(),
      { path: "/etc/docker/daemon.json", content: DOCKER_DAEMON, permissions: "0644" },
      { path: "/etc/convoy/tools", content: tools.join("\n") + "\n", permissions: "0644" },
      { path: "/usr/local/lib/convoy/install-extras.sh", content: installExtrasScript(tailscale, desktop), permissions: "0644" },
    ],

    runcmd: [["bash", "/usr/local/lib/convoy/bootstrap.sh"]],

    // The first-boot upgrade often installs a new kernel. Reboot once, after
    // setup succeeded, so the VM runs it.
    power_state: {
      mode: "reboot",
      condition: ["sh", "-c", "test -f /var/lib/convoy/ready && test -f /var/run/reboot-required"],
      message: "convoy: rebooting to apply updates",
    },
  };

  return `#cloud-config\n${stringify(config, { lineWidth: 0 })}`;
}

/**
 * cloud-init for a VM woken from a sleep snapshot. Everything from the first
 * setup is already on the disk, so this only redoes what a new machine
 * resets: the agent user's SSH key and DigitalOcean's expired root password.
 * The `ready` marker from the first setup is on the disk too, so the CLI's
 * usual setup check works unchanged.
 */
export function buildWakeCloudInit(sshPublicKey: string): string {
  const config = {
    users: [
      {
        name: VM_USER,
        groups: ["sudo"],
        shell: "/bin/bash",
        sudo: "ALL=(ALL) NOPASSWD:ALL",
        ssh_authorized_keys: [sshPublicKey.trim()],
      },
    ],
    disable_root: true,
    ssh_pwauth: false,
    runcmd: [["bash", "-c", 'usermod -L root && chage -d "$(date +%F)" -M -1 root']],
  };
  return `#cloud-config\n${stringify(config, { lineWidth: 0 })}`;
}

/**
 * cloud-init for a new VM launched from a snapshot. Like waking, plus what
 * must differ between copies of one machine: its own Tailscale identity (the
 * CLI joins it afresh) and an empty fail2ban ban list. SSH host keys are
 * regenerated by cloud-init for every new instance.
 *
 * Subscription logins are removed too, so they're never copied between
 * machines (see credentials.ts): Claude Code's OAuth login and a Codex
 * ChatGPT login (an auth.json with tokens). API keys stay. Each copy signs
 * in to plans on its own with `l`.
 */
export function buildRestoreCloudInit(sshPublicKey: string): string {
  const wake = buildWakeCloudInit(sshPublicKey).replace(/^#cloud-config\n/, "");
  const config = {
    // bootcmd runs early on every boot; the marker makes this a first-boot-only step.
    bootcmd: [
      [
        "sh",
        "-c",
        "test -f /var/lib/convoy/restored && exit 0; " +
          "systemctl stop tailscaled 2>/dev/null; rm -f /var/lib/tailscale/tailscaled.state; " +
          "rm -f /var/lib/fail2ban/fail2ban.sqlite3; " +
          `rm -f /home/${VM_USER}/.claude/.credentials.json; ` +
          `f=/home/${VM_USER}/.codex/auth.json; if [ -f $f ] && jq -e '.tokens != null' $f >/dev/null 2>&1; then rm -f $f; fi; ` +
          "mkdir -p /var/lib/convoy; touch /var/lib/convoy/restored",
      ],
    ],
  };
  return `#cloud-config\n${stringify(config, { lineWidth: 0 })}${wake}`;
}
